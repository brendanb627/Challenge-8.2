












































































































































































































































































































































































































import os
import platform
import sys

def shutdown(delay_seconds=0):
    system = platform.system()

    if system == "Windows":
        os.system(f"shutdown /s /t {delay_seconds}")
    elif system == "Darwin":  # macOS
        minutes = max(1, delay_seconds // 60)
        os.system(f"sudo shutdown -h +{minutes}")
    elif system == "Linux":
        minutes = delay_seconds // 60
        os.system(f"shutdown -h +{minutes}" if minutes else "shutdown -h now")
    else:
        print(f"Unsupported OS: {system}")

if __name__ == "__main__":
    delay = int(sys.argv[1]) if len(sys.argv) > 1 else 0
    shutdown(delay)